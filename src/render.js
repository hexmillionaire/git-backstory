// Pure: facts in, markdown out. Short on purpose — an agent reads all of it.

export function render(a, { webUrl = null, range = null, previousPaths = [] } = {}) {
  const L = [];
  const link = (c) => (webUrl ? `[\`${c.short}\`](${webUrl}/commit/${c.hash})` : `\`${c.short}\``);
  const issue = (n) => (webUrl ? `[#${n}](${webUrl}/issues/${n})` : `#${n}`);
  const when = (c) => c.date.slice(0, 10);
  const subj = (c) => c.subject.replace(/\s+/g, " ").trim();
  const title = range ? `${a.file}:${range.start}${range.end !== range.start ? `-${range.end}` : ""}` : a.file;

  L.push(`# History brief: \`${title}\``, "");

  if (a.commitCount === 0) {
    L.push(range ? "No commits touched this range." : "No history for this path. Is it tracked, and is the path relative to the repository root?");
    return L.join("\n") + "\n";
  }

  // Summary line.
  const parts = [];
  parts.push(`${a.commitCount} commit${a.commitCount === 1 ? "" : "s"}`);
  const ago = (d) => (d < 1 ? "today" : `${humanDays(d)} ago`);
  if (a.ageDays != null) parts.push(`first ${when(a.first)} (${ago(a.ageDays)})`);
  if (a.quietDays != null) parts.push(`last ${when(a.last)} (${ago(a.quietDays)})`);
  parts.push(`${a.authors.length} author${a.authors.length === 1 ? "" : "s"}`);
  if (a.lineCount != null && !range) parts.push(`${a.lineCount} lines now`);
  L.push(parts.join(" · "), "");
  if (previousPaths.length) L.push(`Previously at: ${previousPaths.map((p) => `\`${p}\``).join(", ")}`, "");

  // What to be careful about: the section that earns the file.
  const careful = [];
  for (const { revert, target } of a.reverts) {
    careful.push(
      target
        ? `${link(revert)} (${when(revert)}) reverted ${link(target)} "${subj(target)}". Whatever that change did was not safe here; read both before trying it again.`
        : `${link(revert)} (${when(revert)}) is a revert: "${subj(revert)}".`,
    );
  }
  for (const b of a.bursts.slice(0, 2)) {
    const from = when(b[0]);
    const to = when(b[b.length - 1]);
    const shown = b.slice(0, 5).map(link).join(", ") + (b.length > 5 ? `, +${b.length - 5} more` : "");
    careful.push(`${b.length} commits between ${from} and ${to} (${shown}): several attempts in a short window, so the first one didn't hold.`);
  }
  if (a.fixes.length) {
    const shown = a.fixes.slice(0, 5);
    careful.push(`Fix-shaped commits (${a.fixes.length}): ${shown.map((c) => `${link(c)} "${subj(c)}"`).join("; ")}${a.fixes.length > shown.length ? "; …" : ""}.`);
  }
  if (careful.length) {
    L.push("## Be careful", "");
    for (const c of careful) L.push(`- ${c}`);
    L.push("");
  }

  // Reasons the authors wrote down.
  if (a.notes.length) {
    L.push("## Reasons on record", "");
    for (const { commit, line } of a.notes.slice(0, 8)) L.push(`- ${line} — ${link(commit)}, ${when(commit)}`);
    L.push("");
  }

  // Co-change coupling.
  if (a.coChanged.length) {
    L.push("## Usually changes together with", "");
    for (const x of a.coChanged) L.push(`- \`${x.path}\` — ${x.count} of the sampled commits (${Math.round(x.share * 100)}%)`);
    L.push("", "If you change this file, check whether those need the same change.", "");
  }

  // Issues / PRs.
  if (a.refs.length) {
    const shown = a.refs.slice(0, 10);
    L.push("## Referenced issues and PRs", "", shown.map((r) => `${issue(r.number)} (${r.commits.length})`).join(", "), "");
  }

  // Ownership.
  if (a.ownership) {
    const o = a.ownership;
    const people = o.topAuthors.map((x) => `${x.name} ${Math.round(x.share * 100)}%`).join(", ");
    L.push("## Who to ask", "", `Current lines by author: ${people}.`);
    const big = o.topCommits[0];
    if (big && big.share >= 0.5) L.push(`${Math.round(big.share * 100)}% of the current lines come from one commit: ${link(big.commit)} "${subj(big.commit)}".`);
    L.push("");
  } else if (a.authors.length) {
    L.push("## Who to ask", "", a.authors.slice(0, 3).map((x) => `${x.name} (${x.count})`).join(", "), "");
  }

  // Timeline, newest first, compact.
  L.push("## Timeline", "");
  const tl = [...a.reverts.map((r) => r.revert), ...a.fixes, a.first, a.last]
    .filter(Boolean)
    .filter((c, i, arr) => arr.findIndex((x) => x.hash === c.hash) === i)
    .sort((x, y) => new Date(y.date) - new Date(x.date))
    .slice(0, 12);
  // Fill with recent commits if the notable ones are few.
  if (tl.length < 8) {
    const recent = [...a.allCommits ?? []].slice(0, 8 - tl.length);
    for (const c of recent) if (!tl.some((x) => x.hash === c.hash)) tl.push(c);
    tl.sort((x, y) => new Date(y.date) - new Date(x.date));
  }
  for (const c of tl) L.push(`- ${when(c)} ${link(c)} ${subj(c)} — ${c.author}`);
  L.push("");

  const sampled = a.sampleLimit && a.commitCount >= a.sampleLimit ? ` Sampled the latest ${a.sampleLimit} commits; pass --max for more.` : "";
  L.push(`_Generated by git-brief from \`git log\` and \`git blame\`.${sampled}_`);
  return L.join("\n") + "\n";
}

export function humanDays(d) {
  if (d < 1) return "today";
  if (d < 14) return `${d} day${d === 1 ? "" : "s"}`;
  if (d < 60) return `${Math.round(d / 7)} weeks`;
  if (d < 730) return `${Math.round(d / 30)} months`;
  return `${(d / 365).toFixed(1)} years`;
}
